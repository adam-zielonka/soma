export type Language = "pl" | "en";
const storageKey = "soma-language";
export function detectLanguage(
  saved: string | null,
  languages: readonly string[],
): Language {
  if (saved === "pl" || saved === "en") return saved;
  for (const language of languages) {
    const code = language.toLowerCase().split(/[-_]/)[0];
    if (code === "pl" || code === "en") return code;
  }
  return "en";
}
function initialLanguage(): Language {
  let saved: string | null = null;
  try {
    saved = localStorage.getItem(storageKey);
  } catch {
    /* Storage may be blocked. */
  }
  return detectLanguage(
    saved,
    typeof navigator === "undefined"
      ? []
      : navigator.languages?.length
        ? navigator.languages
        : [navigator.language],
  );
}
export let language = initialLanguage();
const listeners = new Set<() => void>();
export function subscribe(listener: () => void) {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}
export function setLanguage(value: Language) {
  language = value;
  try {
    localStorage.setItem(storageKey, value);
  } catch {
    /* Switching still works without persistence. */
  }
  updateDocument();
  listeners.forEach((listener) => listener());
}
export function t(
  source: string,
  values: Record<string, string | number> = {},
): string {
  const key = source.replace(/\s+/g, " ").trim();
  const translated = language === "en" ? (translations[key] ?? key) : key;
  return typography(
    translated.replace(/\{(\w+)\}/g, (match, key: string) =>
      String(values[key] ?? match),
    ),
  );
}

